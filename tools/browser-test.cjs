/* Optional browser integration suite. Requires Playwright and a Chromium browser. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const { createServer } = require('./serve-demo.cjs');

(async () => {
  const server = createServer();
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const url = `http://127.0.0.1:${server.address().port}`;
  const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || undefined });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  let nativeDeleteEvents = 0;
  await page.exposeFunction('nativeDelete', () => nativeDeleteEvents++);
  const results = [];
  results.push = function (...items) { for (const item of items) console.log(`PASS ${item}`); return Array.prototype.push.apply(this, items); };
  const waitIndexed = () => page.waitForFunction(() => window.readercDemo?.controller.pages.size && [...readercDemo.controller.pages.values()].some(p => p.hits.length));
  const hit = lemma => page.evaluate(key => {
    const candidate = [...readercDemo.controller.pages.values()].flatMap(x => x.hits).find(x => x.word.lemma === key);
    if (!candidate) return null;
    const rect = candidate.rects[0];
    return { x: (rect.left + rect.right) / 2, y: (rect.top + rect.bottom) / 2 };
  }, lemma);
  const hover = async lemma => {
    const point = await hit(lemma);
    assert.ok(point, `Missing candidate ${lemma}`);
    await page.mouse.move(point.x, point.y);
    const frame = page.frameLocator('iframe[data-readerc-owned="popover"]');
    await frame.locator('.gloss').waitFor();
    await frame.locator('.gloss').filter({ hasText: /[\u3400-\u9fff]/ }).waitFor();
    return frame;
  };
  try {
    await page.goto(url);
    await waitIndexed();
    const originalText = await page.locator('.textLayer').innerHTML();
    assert.ok(await page.locator('[data-readerc-owned="markers"] span').count() > 10);
    results.push('automatic markers from full bundled dictionary');
    await page.evaluate(() => document.addEventListener('keydown', e => { if (e.key === 'Delete') window.nativeDelete(); }, true));
    await page.keyboard.press('Delete');
    assert.equal(Object.keys(await page.evaluate(() => readercDemo.host.getVocabulary())).length, 0);
    assert.equal(nativeDeleteEvents, 1);
    results.push('Delete outside the card remains a native reader event');
    let card = await hover('attenuate');
    assert.match(await card.locator('.gloss').innerText(), /[\u3400-\u9fff]/);
    assert.equal(await card.locator('body').innerText(), '减弱');
    assert.equal(await card.locator('body button, body header, body small, .sentence').count(), 0);
    const minimal = await card.locator('.gloss').evaluate(el => ({ border: getComputedStyle(el).borderWidth, shadow: getComputedStyle(el).boxShadow }));
    assert.equal(minimal.border, '0px'); assert.equal(minimal.shadow, 'none');
    const popupSize = await page.locator('iframe[data-readerc-owned="popover"]').boundingBox();
    assert.ok(popupSize.width < 100 && popupSize.height <= 28);
    results.push('hover displays exactly one Chinese gloss, with no border, buttons or sentence');
    await card.locator('.gloss').click();
    await page.keyboard.press('Delete');
    await page.waitForFunction(() => readercDemo.host.getVocabulary().attenuate?.state === 'known');
    assert.equal(nativeDeleteEvents, 1);
    await page.waitForFunction(() => ![...readercDemo.controller.pages.values()].some(s => s.hits.some(h => h.word.lemma === 'attenuate')));
    results.push('card Delete marks lemma known and cannot reach native annotation shortcuts');
    await page.locator('[data-readerc-owned="toast"] button').click();
    await page.waitForFunction(() => !readercDemo.host.getVocabulary().attenuate);
    await page.waitForFunction(() => [...readercDemo.controller.pages.values()].some(s => s.hits.some(h => h.word.lemma === 'attenuate')));
    assert.ok(await hit('attenuate'));
    results.push('undo restores vocabulary and marker');
    card = await hover('attenuate');
    await card.locator('.gloss').click();
    await page.keyboard.press('Delete');
    await page.waitForFunction(() => readercDemo.host.getVocabulary().attenuate?.state === 'known');
    await page.reload();
    await waitIndexed();
    assert.equal(await hit('attenuate'), null);
    results.push('known vocabulary persists across reload');
    await page.getByRole('button', { name: '阅读设置' }).click();
    await page.getByPlaceholder('搜索熟词或生词').fill('attenuate');
    await page.locator('.rc-word').getByRole('button', { name: '恢复默认' }).click();
    await page.getByRole('button', { name: '关闭设置' }).click();
    await page.waitForFunction(() => [...readercDemo.controller.pages.values()].some(s => s.hits.some(h => h.word.lemma === 'attenuate')));
    assert.equal(await page.locator('.textLayer').innerHTML(), originalText);
    results.push('settings restore familiarity; PDF text layer is never rewritten');
    await page.evaluate(() => { document.querySelector('.page').style.zoom = '1.2'; window.dispatchEvent(new Event('resize')); });
    await page.waitForTimeout(300);
    const alignmentError = await page.evaluate(() => {
      const state = [...readercDemo.controller.pages.values()][0];
      const expected = state.hits[0].range.getClientRects()[0];
      const marker = state.overlay.firstElementChild.getBoundingClientRect();
      return Math.abs(marker.left - expected.left) + Math.abs(marker.width - expected.width);
    });
    assert.ok(alignmentError < 3, `Zoom alignment error ${alignmentError}`);
    results.push('markers track PDF zoom without changing text geometry');
    await page.evaluate(() => { document.querySelector('.page').style.zoom = ''; window.dispatchEvent(new Event('resize')); });
    await page.waitForTimeout(300);
    await page.getByRole('button', { name: '词释 ON' }).click();
    await page.waitForFunction(() => !document.querySelector('[data-readerc-owned="markers"]'));
    await page.getByRole('button', { name: '词释 OFF' }).click();
    await waitIndexed();
    results.push('reader toolbar toggles the entire overlay');
    await page.getByRole('button', { name: '阅读设置' }).click();
    await page.getByLabel('批量编辑词条').fill('novelmarker\ncell culture');
    await page.getByRole('button', { name: '标记为生词', exact: true }).click();
    await page.waitForFunction(() => readercDemo.host.getVocabulary()['cell culture']?.state === 'unknown');
    await page.locator('summary').filter({ hasText: '备份与导入词表' }).click();
    await page.getByRole('button', { name: '生成备份 JSON' }).click();
    const exported = JSON.parse(await page.getByLabel('词表 JSON').inputValue());
    assert.equal(exported.vocabulary.novelmarker.state, 'unknown');
    assert.equal(exported.config, undefined);
    await page.getByRole('button', { name: '关闭设置' }).click();
    results.push('custom words and phrases can be added and exported');
    // Test character data changes made by the rendering engine.
    await page.evaluate(() => {
      const text = document.createElement('p'); text.id = 'mutation-test'; text.textContent = 'An ordinary response.';
      document.querySelector('.textLayer').append(text);
    });
    await page.waitForTimeout(250);
    await page.evaluate(() => { document.getElementById('mutation-test').firstChild.nodeValue = 'novelmarker cell culture'; });
    await page.waitForFunction(() => [...readercDemo.controller.pages.values()].some(s => s.hits.some(h => h.word.lemma === 'novelmarker')));
    results.push('rendered text changes trigger reindexing, including custom phrases');
    await page.evaluate(() => document.getElementById('mutation-test').remove());
    await page.waitForTimeout(250);
    card = await hover('attenuate');
    await card.locator('.gloss').click();
    await page.keyboard.press('Escape');
    await page.locator('iframe[data-readerc-owned="popover"]').waitFor({ state: 'detached' });
    results.push('Escape dismisses the card');
    const outputDir = path.join(__dirname, '..', 'test-results');
    fs.mkdirSync(outputDir, { recursive: true });
    card = await hover('attenuate');
    await page.screenshot({ path: path.join(outputDir, 'readerc-demo.png') });
    await page.evaluate(() => readercDemo.controller.destroy());
    assert.equal(await page.locator('[data-readerc-owned]').count(), 0);
    assert.deepEqual(errors, []);
    results.push('disabling removes observers, markers and popovers cleanly');
    fs.writeFileSync(path.join(outputDir, 'browser-results.json'), JSON.stringify({ passed: results, pageErrors: errors }, null, 2));
    console.log(`Browser checks: ${results.length} passed.`);
  } finally {
    await browser.close();
    await new Promise(resolve => server.close(resolve));
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
